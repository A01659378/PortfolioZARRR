import torch
from torch.utils.data import Dataset, Subset

class TransformedSubset(Dataset):
    def __init__(self, subset, transform=None):
        # subset: subconjunto creado con random_split()
        # transform: transformaciones específicas para este subconjunto
        self.subset = subset
        self.transform = transform

    def __getitem__(self, index):
        # Recuperamos la imagen y etiqueta del subset original
        x, y = self.subset[index]
        if self.transform:
            x = self.transform(x)

        # Regresamos imagen transformada + etiqueta
        return x, y

    def __len__(self):
        return len(self.subset)

