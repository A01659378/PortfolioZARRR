"""# Arquitectura

### Justificación de la arquitectura CNN

La arquitectura implementada está compuesta por tres bloques convolucionales seguidos de un clasificador completamente conectado. Cada bloque incluye:
- Convoluciones 3x3  
- Batch Normalization  
- Función de activación ReLU  
- MaxPooling  

**Tamaño de filtros (3x3):**  
Los filtros 3x3 son un estándar en CNN modernas porque permiten capturar bordes y texturas locales manteniendo bajo el número de parámetros. Esto mejora la eficiencia y facilita el entrenamiento.

**Aumento progresivo del número de canales (16 → 32 → 64 → 128):**  
Este incremento permite que la red aprenda una jerarquía de características:  
- Primer bloque: patrones simples como bordes.  
- Segundo bloque: estructuras intermedias del rostro.  
- Tercer bloque: patrones de alto nivel asociados a expresiones emocionales.  

**Número de capas:**  
Se eligieron tres bloques porque las imágenes del dataset (48x48) son pequeñas y no requieren redes profundas. Tres etapas son suficientes para extraer características relevantes sin caer en overfitting.

**Funciones de activación ReLU:**  
ReLU acelera la convergencia, evita el desvanecimiento del gradiente y funciona muy bien en arquitecturas profundas.

**Regularización utilizada:**  
- **Batch Normalization:** estabiliza las activaciones y permite entrenar más rápido y de manera más estable.  
- **Dropout (0.5):** reduce significativamente el overfitting en las capas densas apagando neuronas aleatoriamente.  
- **Data Augmentation:** rotaciones y flips aleatorios aumentan la variabilidad del dataset, mejorando la capacidad de generalización.  
- **Early Stopping:** previene overfitting deteniendo el proceso cuando el modelo deja de mejorar en validación.

Estas decisiones equilibran capacidad de representación, estabilidad durante el entrenamiento y control del overfitting.
"""

class CNNModel(nn.Module):
    def __init__(self, num_classes=2):
        super(CNNModel, self).__init__()
        # Primer bloque convolucional
        self.features = nn.Sequential(
            # Bloque 1
            # Patrones simples
            nn.Conv2d(1, 16, kernel_size=3, padding=1), # Los canales de entrada cambiaron a 1 para escala de grises
            nn.BatchNorm2d(16),
            nn.ReLU(),
            nn.Conv2d(16, 16, kernel_size=3, padding=1),
            nn.BatchNorm2d(16),
            nn.ReLU(),
            nn.MaxPool2d(kernel_size=2, stride=2),    # Tamaño de salida: 16x24x24 (desde 16x48x48)
            # Esto hace la red más eficiente y mejora la recepción de nuevos datos

            # Bloque 2
            # Patrones intermedios
            nn.Conv2d(16, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.Conv2d(32, 64, kernel_size=3, padding=1), # Filtros aumentados a 64
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(kernel_size=2, stride=2),    # Tamaño de salida: 64x12x12 (desde 64x24x24)

            # Bloque 3
            # Patrones completos: ojos, cejas, boca
            nn.Conv2d(64, 128, kernel_size=3, padding=1), # Filtros aumentados a 128
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.Conv2d(128, 128, kernel_size=3, padding=1), # Mantener filtros en 128
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.MaxPool2d(kernel_size=2, stride=2)     # Tamaño de salida: 128x6x6 (desde 128x12x12)
        )

        # Clasificador (Capas densas)
        # Entrada a la capa lineal después de 3 capas MaxPool2d (48x48 -> 24x24 -> 12x12 -> 6x6)
        # Canales finales: 128
        self.classifier = nn.Sequential(
            nn.Dropout(0.5), #Evita el sobreajuste apagando aleatoriamente neuronas.
            nn.Linear(128 * 6 * 6, 1024), # Primera capa densa
            nn.ReLU(),
            nn.Dropout(0.5), # Segundo dropout
            nn.Linear(1024, 512), # Segunda capa densa
            nn.ReLU(),
            nn.Dropout(0.5), # Tercero dropout
            nn.Linear(512, num_classes) # Capa de salida con 2 clases
        )

    def forward(self, x):
        x = self.features(x)
        x = x.view(x.size(0), -1)  # Aplanar la salida para las capas completamente conectadas
        x = self.classifier(x)
        return x

