"""# Modelo

## Entrenamiento del modelo

En esta sección se realiza el proceso completo de entrenamiento del modelo.  
El entrenamiento se ejecuta durante un máximo de **50 épocas**, registrando en cada una:

- **Loss de entrenamiento (train loss)**
- **Accuracy de entrenamiento**
- **Loss de validación (test loss)**
- **Accuracy de validación**

Esto permite analizar el progreso del aprendizaje y monitorear si el modelo está generalizando bien.

### Función de pérdida
Se utiliza `CrossEntropyLoss`, que es la función estándar para tareas de **clasificación multiclase**.  
Esta función compara los *logits* del modelo contra las etiquetas verdaderas y calcula el error que se utilizará para ajustar los pesos.

### Optimización mediante Backpropagation
En cada batch de entrenamiento se ejecutan los pasos clásicos:
1. **Forward pass**: el modelo genera una predicción.
2. **Cálculo del loss**.
3. **Backward pass**: se calculan gradientes.
4. **Actualización de pesos** mediante el optimizador Adam.

### Validación por época
Después de entrenar cada época, el modelo se evalúa sobre el conjunto de prueba:
- No se calculan gradientes (`torch.no_grad()`).
- No se aplican augmentations (solo `test_transforms`).
- Se calcula accuracy y loss de validación para medir generalización.

Esto permite comparar el desempeño entre *train* y *test* y detectar señales de overfitting.

### Early Stopping
Se implementa un mecanismo de **early stopping** para evitar overfitting.  
Este mecanismo detiene el entrenamiento si:

- El **test loss** no mejora durante `patience = 5` épocas consecutivas.
- La mejora mínima requerida es `min_delta = 0.001`.

Cada vez que el modelo mejora su desempeño en validación, se guardan sus **mejores pesos** (`best_model_state`).  
Al finalizar, se recargan dichos pesos para asegurar que el modelo final utilizado sea el mejor observado durante todo el entrenamiento.
"""

num_epochs = 50
train_losses = []
train_accuracies = []
test_losses = []
test_accuracies = []

# Cambiar la función de pérdida a CrossEntropyLoss
criterion = nn.CrossEntropyLoss()

model.to(device) # Asegurar que el modelo esté en el dispositivo correcto antes de comenzar el entrenamiento

# Parámetros de Early Stopping
best_test_loss = float('inf')
patience = 5
patience_counter = 0
min_delta = 0.001 # Cambio mínimo en la pérdida de prueba para ser considerado una mejora
best_model_state = None # Para almacenar los mejores pesos del modelo

for epoch in range(num_epochs):
    model.train() # Establecer el modelo en modo de entrenamiento
    total_train_loss = 0.0
    correct_predictions_train = 0
    total_samples_train = 0

    # Training loop
    for batch_idx, (inputs, labels) in enumerate(tqdm(train_dataloader, desc=f"Epoch {epoch+1} Training")):
        inputs, labels = inputs.to(device), labels.to(device)

        # Forward pass
        outputs = model(inputs)

        loss = criterion(outputs, labels)

        # Backpropagation and optimization
        optimizer.zero_grad() # Borrar gradientes anteriores
        loss.backward()       # Calcular gradientes
        optimizer.step()      # Actualizar parámetros del modelo

        total_train_loss += loss.item() * inputs.size(0)

        # Para clasificación multiclase, obtener predicciones encontrando el logit máximo
        _, predicted = torch.max(outputs.data, 1)

        # Asegurarse de que las etiquetas sean 'long' para la comparación con lo predicho
        correct_predictions_train += (predicted == labels).sum().item()
        total_samples_train += labels.size(0) # Usar labels.size(0) ya que es batch_size

    avg_train_loss = total_train_loss / total_samples_train
    train_accuracy = correct_predictions_train / total_samples_train
    train_losses.append(avg_train_loss)
    train_accuracies.append(train_accuracy)

    # Evaluation phase
    model.eval() # Establecer el modelo en modo de evaluación
    total_test_loss = 0.0
    correct_predictions_test = 0
    total_samples_test = 0

    with torch.no_grad(): # Deshabilitar el cálculo de gradientes para la evaluación
        for inputs, labels in tqdm(test_dataloader, desc=f"Epoch {epoch+1} Testing"):
            inputs, labels = inputs.to(device), labels.to(device)

            outputs = model(inputs)
            loss = criterion(outputs, labels)

            total_test_loss += loss.item() * inputs.size(0)

            _, predicted = torch.max(outputs.data, 1)
            correct_predictions_test += (predicted == labels).sum().item()
            total_samples_test += labels.size(0)

    avg_test_loss = total_test_loss / total_samples_test
    test_accuracy = correct_predictions_test / total_samples_test
    test_losses.append(avg_test_loss)
    test_accuracies.append(test_accuracy)

    print(f"Epoch [{epoch+1}/{num_epochs}], Train Loss: {avg_train_loss:.4f}, Train Accuracy: {train_accuracy:.4f}, Test Loss: {avg_test_loss:.4f}, Test Accuracy: {test_accuracy:.4f}")

    # Early stopping
    if avg_test_loss < best_test_loss - min_delta:
        best_test_loss = avg_test_loss
        patience_counter = 0
        best_model_state = model.state_dict() # Guardar los mejores pesos del modelo
    else:
        patience_counter += 1
        if patience_counter >= patience:
            print(f"Early stopping triggered after {epoch+1} epochs due to no improvement in test loss for {patience} consecutive epochs.")
            break

# Cargar los mejores pesos del modelo si se produjo una detención temprana
if best_model_state is not None:
    model.load_state_dict(best_model_state)
    print("Loaded best model weights due to early stopping.")

