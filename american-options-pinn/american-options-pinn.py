"""## Sección 3. Método binomial americano

El árbol binomial se utiliza como método clásico de referencia para valuar la opción put americana. En cada nodo del árbol se calcula el valor de continuación y se compara contra el valor de ejercer inmediatamente.

Esta comparación permite incorporar la característica principal de las opciones americanas: la posibilidad de ejercicio anticipado. Además, el método binomial permite estimar una frontera óptima de ejercicio, que posteriormente se utiliza para comparar la frontera aprendida por la PINN.

<br>

De manera similar al artículo, se utiliza el método binomial como referencia numérica para validar los resultados de la PINN. Adicionalmente, se extrae la frontera óptima de ejercicio y se incorpora como información auxiliar durante el entrenamiento.
"""

def american_put_binomial(S0, K, r, sigma, T, N):
    dt = T / N
    u = np.exp(sigma * np.sqrt(dt))
    d = 1 / u
    disc = np.exp(-r * dt)
    q = (np.exp(r * dt) - d) / (u - d)

    # precios al vencimiento
    S = np.array([S0 * u**j * d**(N-j) for j in range(N+1)])
    V = np.maximum(K - S, 0)

    boundary = []

    for step in range(N-1, -1, -1):
        # reconstruir correctamente los precios en este tiempo
        S = np.array([S0 * u**j * d**(step-j) for j in range(step+1)])

        continuation = disc * ((1-q) * V[:step+1] + q * V[1:step+2])
        exercise = np.maximum(K - S, 0)

        V = np.maximum(continuation, exercise)

        exercise_nodes = S[(exercise > 0) & (exercise >= continuation)]

        if len(exercise_nodes) > 0:
            boundary.append([step * dt, np.max(exercise_nodes)])
        else:
            boundary.append([step * dt, np.nan])

    boundary = np.array(boundary[::-1])
    return V[0], boundary

N_binomial = 300
