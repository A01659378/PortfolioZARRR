"""## Sección 5. Arquitectura de la PINN y Frontera Móvil

El modelo utiliza dos redes neuronales.

* La primera aproxima el precio de la opción $V(S,t)$, recibiendo como entradas el precio del activo $S$ y el tiempo $t$.
* La segunda red aproxima la frontera óptima de ejercicio $B(t)$.

<br>

Al igual que en el artículo, se emplean dos redes neuronales: una para aproximar el precio de la opción y otra para aproximar la frontera libre. No obstante, se adopta una arquitectura PINN directa, prescindiendo de la solución aproximada parametrizada y de la capa de expansión de datos propuestas en el trabajo original.

### Red para el precio de la opción $V(S,t)$
"""

# Red para el precio de la opción V(S,t)
class PINN(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(2, 64),
            nn.Tanh(),
            nn.Linear(64, 64),
            nn.Tanh(),
            nn.Linear(64, 64),
            nn.Tanh(),
            nn.Linear(64, 1),
            nn.Softplus()
        )

    def forward(self, S, t):
        S_norm = S / Smax
        t_norm = t / T
        x = torch.cat([S_norm, t_norm], dim=1)
        V_norm = self.net(x)
        return K * V_norm

"""### Red para la frontera móvil S*(t)

Se incorporó conocimiento financiero básico al modelo para que la frontera aprendida permaneciera por debajo del strike $K$, ya que una frontera por encima de ese valor no tendría interpretación financiera para una opción put americana. Esta restricción mejora la estabilidad del entrenamiento sin imponer la solución exacta.
"""

# Red para la frontera móvil S*(t)
class BoundaryNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(1, 32),
            nn.Tanh(),
            nn.Linear(32, 32),
            nn.Tanh(),
            nn.Linear(32, 1),
            nn.Sigmoid()
        )

    def forward(self, t):
        t_norm = t / T

        # La frontera de una put americana debe estar por debajo de K.
        # La acotamos a una región financieramente razonable: [K - 0.15K, K]
        lower = 0.85 * K
        upper = K

        return lower + (upper - lower) * self.net(t_norm)

model = PINN().to(device)
boundary_model = BoundaryNet().to(device)

optimizer = torch.optim.Adam(
    list(model.parameters()) + list(boundary_model.parameters()),
    lr=1e-3
)

"""## Sección 6. Puntos de colocación

En esta sección se definen los puntos de colocación utilizados durante el entrenamiento. Los puntos interiores se emplean para evaluar el residuo de la ecuación de Black-Scholes, mientras que otros conjuntos de puntos se usan para imponer la condición terminal, las condiciones de frontera y la comparación con el método binomial.

Separar estos puntos permite identificar con claridad dónde se evalúa cada término de la función de pérdida.

<br>

De forma similar al artículo, el entrenamiento se realiza mediante puntos interiores y puntos asociados a las condiciones de frontera y terminales. Para simplificar la implementación, se utiliza únicamente muestreo uniforme dentro del dominio de entrenamiento.
"""

def generar_puntos_colocacion(n_pde=2000, n_bc=500, n_data=300):
    # Puntos interiores para el residuo de Black-Scholes
    S_pde = torch.rand(n_pde, 1).to(device) * Smax
    t_pde = torch.rand(n_pde, 1).to(device) * T

    # Puntos para condición terminal t = T
    S_T = torch.linspace(0, Smax, n_bc).reshape(-1,1).to(device)
    t_T = T * torch.ones_like(S_T).to(device)

    # Puntos para fronteras S = 0 y S = Smax
    t_b = torch.linspace(0, T, n_bc).reshape(-1,1).to(device)
    S_0 = torch.zeros_like(t_b).to(device)
    S_m = Smax * torch.ones_like(t_b).to(device)

    # Puntos de datos binomiales
    idx = np.random.choice(len(S_grid), n_data, replace=True)
    S_data_np = S_grid[idx].reshape(-1,1)
    V_data_np = V_binomial_grid[idx].reshape(-1,1)

    S_data = torch.tensor(S_data_np, dtype=torch.float32).to(device)
    t_data = torch.zeros_like(S_data).to(device)
    V_data = torch.tensor(V_data_np, dtype=torch.float32).to(device)

    return S_pde, t_pde, S_T, t_T, t_b, S_0, S_m, S_data, t_data, V_data

"""## Sección 7. Función de pérdida

La función de pérdida combina restricciones matemáticas, financieras y datos de referencia.

Incluye:
* El residuo de la ecuación de Black-Scholes
* La condición terminal al vencimiento
* Las condiciones de frontera
* La restricción americana $V(S,t)\geq \max(K-S,0)$
* Comparación contra precios generados por el método binomial.

También se incorporan condiciones sobre la frontera móvil:

* La condición de valor $V(B(t),t)=K-B(t)$
* La condición de smooth pasting $V_S(B(t),t)=-1$
* Pérdida adicional que guía la frontera de la PINN con la frontera obtenida por el método binomial.

<br>

La función de pérdida conserva los términos físicos principales utilizados en el artículo, incluyendo el residuo de la ecuación diferencial y las condiciones asociadas a la frontera libre. Adicionalmente, se incorporan términos supervisados basados en precios y fronteras obtenidos mediante el método binomial, así como restricciones financieras propias de las opciones americanas.
"""

def pinn_loss(model, n_pde=2000, n_bc=500, n_data=300):
    # Se llaman los puntos de colocación definidos en la sección anterior
    S, t, S_T, t_T, t_0, S_0, S_m, S_data, t_data, V_data = generar_puntos_colocacion(
        n_pde=n_pde,
        n_bc=n_bc,
        n_data=n_data
    )

    # Activamos gradientes en puntos interiores para calcular derivadas
    S.requires_grad = True
    t.requires_grad = True

    # Residuo de Black-Scholes
    V = model(S, t)

    V_S = autograd.grad(
        V, S,
        grad_outputs=torch.ones_like(V),
        create_graph=True
    )[0]

    V_t = autograd.grad(
        V, t,
        grad_outputs=torch.ones_like(V),
        create_graph=True
    )[0]

    V_SS = autograd.grad(
        V_S, S,
        grad_outputs=torch.ones_like(V_S),
        create_graph=True
    )[0]

    residual = V_t + 0.5*sigma**2*S**2*V_SS + r*S*V_S - r*V
    loss_pde = torch.mean(residual**2)

    # Condición terminal: V(S,T) = max(K-S,0)
    V_T = model(S_T, t_T)
    payoff_T = torch.maximum(K - S_T, torch.zeros_like(S_T))
    loss_terminal = torch.mean((V_T - payoff_T)**2)

    # Frontera S = 0
    V_0 = model(S_0, t_0)
    target_0 = K * torch.exp(-r * (T - t_0))
    loss_s0 = torch.mean((V_0 - target_0)**2)

    # Frontera S = Smax
    V_m = model(S_m, t_0)
    loss_smax = torch.mean(V_m**2)

    # Condición americana: V >= payoff
    payoff_interior = torch.maximum(K - S, torch.zeros_like(S))
    loss_american = torch.mean(torch.relu(payoff_interior - V)**2)

    # Datos binomiales en t = 0
    V_pred_data = model(S_data, t_data)
    loss_data = torch.mean((V_pred_data - V_data)**2)

    # Frontera móvil aproximada por la red BoundaryNet
    S_b = boundary_model(t_0)

    V_b = model(S_b, t_0)
    payoff_b = K - S_b

    # Condición de valor sobre la frontera: V(B(t),t) = K - B(t)
    loss_boundary_value = torch.mean((V_b - payoff_b)**2)

    # Smooth pasting: V_S(B(t),t) = -1
    V_S_b = autograd.grad(
        V_b, S_b,
        grad_outputs=torch.ones_like(V_b),
        create_graph=True
    )[0]

    # Datos de frontera binomial para guiar B_PINN(t)

    idx_b = np.random.choice(
        len(boundary_times_clean),
        min(n_bc, len(boundary_times_clean)),
        replace=True
    )

    t_boundary_np = boundary_times_clean[idx_b].reshape(-1,1)
    B_boundary_np = boundary_values_clean[idx_b].reshape(-1,1)

    t_boundary = torch.tensor(
        t_boundary_np,
        dtype=torch.float32
    ).to(device)

    B_boundary = torch.tensor(
        B_boundary_np,
        dtype=torch.float32
    ).to(device)

    B_pred = boundary_model(t_boundary)

    loss_boundary_data = torch.mean(
        (B_pred - B_boundary)**2
    )

    loss_boundary_derivative = torch.mean((V_S_b + 1)**2)

    total_loss = (
        loss_pde
        + 10*loss_terminal
        + loss_s0
        + loss_smax
        + 5*loss_american
        + 5*loss_data
        + 10*loss_boundary_value
        + 5*loss_boundary_derivative
        + 10*loss_boundary_data
    )

    return total_loss, loss_pde, loss_terminal, loss_data

"""## Sección 8. Entrenamiento

Durante el entrenamiento se minimiza la pérdida total mediante el optimizador Adam.

<br>

El procedimiento de entrenamiento sigue el esquema general descrito en el artículo mediante optimización conjunta de ambas redes utilizando Adam. La principal diferencia es la incorporación de información supervisada proveniente del método binomial y la utilización de una configuración de entrenamiento más compacta.
"""

epochs = 5000
loss_history = []

for epoch in range(epochs):
    optimizer.zero_grad()

    loss, loss_pde, loss_terminal, loss_data = pinn_loss(model)
    loss.backward()
    optimizer.step()

    loss_history.append(loss.item())

    if epoch % 500 == 0:
        print(
            f"Epoch {epoch} | Loss: {loss.item():.6f} | "
            f"PDE: {loss_pde.item():.6f} | "
            f"Terminal: {loss_terminal.item():.6f} | "
            f"Data: {loss_data.item():.6f}"
        )

plt.figure(figsize=(7,4))
plt.plot(loss_history)
plt.yscale("log")
plt.xlabel("Época")
plt.ylabel("Loss")
plt.title("Evolución de la pérdida")
plt.grid(True)
plt.show()

