class BusquedaMin(SearchProblem):
    def __init__(self, ambiente, posicion_inicial):
        self.ambiente = ambiente
        self.posicion_inicial = posicion_inicial
        self.initial_state = (posicion_inicial, 100, [posicion_inicial])
        super().__init__(initial_state=self.initial_state)

    def actions(self, state):
        (x, y), gasolina, movimientos = state
        acciones = []
        posibles_movimientos = [
            (-1, 0), (1, 0), (0, -1), (0, 1),  # Movimientos verticales y horizontales
            (-1, -1), (-1, 1), (1, -1), (1, 1)  # Movimientos diagonales
        ]

        for dx, dy in posibles_movimientos:
            nuevo_x, nuevo_y = x + dx, y + dy
            if 0 <= nuevo_x < self.ambiente.filas and 0 <= nuevo_y < self.ambiente.columnas:
                nivel_actual = self.ambiente.obtener_nivel((x, y))
                nuevo_nivel = self.ambiente.obtener_nivel((nuevo_x, nuevo_y))
                if isinstance(nuevo_nivel, int) and abs(nivel_actual - nuevo_nivel) == 1 and nuevo_nivel != ' X' and nuevo_nivel != ' ~':
                    costo_movimiento = nuevo_nivel + 1
                    nueva_gasolina = max(0, gasolina - costo_movimiento)
                    if nueva_gasolina > 0:
                        acciones.append((dx, dy))

        return acciones if acciones else []

    def result(self, state, action):
        (x, y), gasolina, movimientos = state
        dx, dy = action
        nuevo_x, nuevo_y = x + dx, y + dy
        nuevo_nivel = self.ambiente.obtener_nivel((nuevo_x, nuevo_y))
        costo_movimiento = nuevo_nivel + 1
        nueva_gasolina = max(0, gasolina - costo_movimiento)
        nuevo_movimientos = movimientos + [(nuevo_x, nuevo_y)]
        return ((nuevo_x, nuevo_y), nueva_gasolina, nuevo_movimientos)

    def value(self, state):
        (x, y), _, _ = state
        return -self.ambiente.mapa_original[x][y]

    def temperature(self, time):
        return max(0.1, 100 - time)  # Annealing Schedule

