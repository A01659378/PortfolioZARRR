class Nave:
    def __init__(self, nombre, posicion, gasolina):
        self.nombre = nombre
        self.posicion = posicion
        self.gasolina = gasolina

    def actualizar_posicion(self, nueva_posicion):
        self.posicion = nueva_posicion

    def gastar_gas(self, cantidad):
        self.gasolina -= cantidad

    def mandar_coordenadas(self):
        return self.posicion

    def mover(self, direccion, ambiente):
        x, y = self.posicion

        movimientos = {
            "arriba": (-1, 0),
            "abajo": (1, 0),
            "izquierda": (0, -1),
            "derecha": (0, 1),
            "diagonal_arriba_i": (-1, -1),
            "diagonal_arriba_d": (-1, 1),
            "diagonal_abajo_i": (1, -1),
            "diagonal_abajo_d": (1, 1),
        }

        if direccion in movimientos:
            dx, dy = movimientos[direccion]
            nuevo_x = x + dx
            nuevo_y = y + dy

            if not (0 <= nuevo_x < ambiente.filas and 0 <= nuevo_y < ambiente.columnas):
                print(f"La nave {self.nombre} no puede salir del mapa.")
                return

            valor_actual = ambiente.mapa_original[x][y]
            valor_nuevo = ambiente.mapa_original[nuevo_x][nuevo_y]

            if abs(valor_actual - valor_nuevo) > 1:
                print(f"La nave {self.nombre} no puede moverse porque el cambio en el nivel topográfico es mayor a 1. {valor_actual} → {valor_nuevo}")
                return

            if ambiente.mapa[nuevo_x][nuevo_y] == ' X':
                print(f"La nave {self.nombre} no puede moverse porque hay un obstáculo.")
                return

            if ambiente.mapa[nuevo_x][nuevo_y] == ' ~':
                print(f"¡La nave {self.nombre} ha encontrado agua!")
                return

            nivel_nuevo = ambiente.obtener_nivel((nuevo_x, nuevo_y))
            self.gastar_gas(nivel_nuevo)
            ambiente.actualizar_mapa(self, (nuevo_x, nuevo_y))


class Ambiente:
    def __init__(self, filas, columnas, cantidad_agua, cantidad_obstaculos, nave):
        self.filas = filas
        self.columnas = columnas
        self.nave = nave
        self.cantidad_agua = cantidad_agua
        self.cantidad_obstaculos = cantidad_obstaculos
        self.mapa = [[random.choice([0, 1, 2, 3, 4, 5]) for _ in range(columnas)] for _ in range(filas)]
        self.mapa_original = [fila[:] for fila in self.mapa]

        self.distribuir_elementos(cantidad_agua, ' ~')
        self.distribuir_elementos(cantidad_obstaculos, ' X')
        self.colocar_nave()

    def distribuir_elementos(self, cantidad, elemento):
        for _ in range(cantidad):
            while True:
                x = random.randint(0, self.filas - 1)
                y = random.randint(0, self.columnas - 1)
                if isinstance(self.mapa[x][y], int):
                    self.mapa[x][y] = elemento
                    break


    def colocar_nave(self):
        x, y = self.nave.posicion
        self.mapa[x][y] = '\033[1m N\033[0m'

    def actualizar_mapa(self, nave, nueva_posicion, nueva_gasolina):
        x_actual, y_actual = nave.posicion
        nueva_x, nueva_y = nueva_posicion

        # Restaura el valor original en la posición actual
        self.mapa[x_actual][y_actual] = self.mapa_original[x_actual][y_actual]

        # Mueve la nave a la nueva posición y actualiza la gasolina
        nave.actualizar_posicion(nueva_posicion)
        nave.gasolina = nueva_gasolina  # Actualiza el nivel de gasolina de la nave
        self.mapa[nueva_x][nueva_y] = '\033[1m N\033[0m'

    def mostrar_mapa(self):
        print(f'Mapa de {self.filas}x{self.columnas}:')
        print(f'Asigno nave {self.nave.nombre} como N')
        print(f"Nivel de gasolina {self.nave.gasolina} litros")
        print(f'Cantidad de agua {self.cantidad_agua}')
        print(f'Cantidad de obstáculos {self.cantidad_obstaculos}')
        print('_' * (self.columnas * 3 + 3))
        for fila in self.mapa:
            print('|' + " ".join(f'{value:2}' for value in fila) + '|')
        print('_' * (self.columnas * 3 + 3))

    def obtener_nivel(self, posicion):
        x, y = posicion
        if 0 <= x < self.filas and 0 <= y < self.columnas:
            return self.mapa_original[x][y]
        return None

class BusquedaAgua(SearchProblem):
    def __init__(self, nave, ambiente):
        self.nave = nave
        self.ambiente = ambiente
        super().__init__(initial_state=(nave.posicion, nave.gasolina))

    def actions(self, state):
        """ Devuelve las acciones válidas desde el estado actual """
        (x, y), gasolina = state
        movimientos = {
            "derecha": (0, 1),
            "abajo": (1, 0),
            "izquierda": (0, -1),
            "arriba": (-1, 0),
            "diagonal_abajo_derecha": (1, 1),
            "diagonal_abajo_izquierda": (1, -1),
            "diagonal_arriba_derecha": (-1, 1),
            "diagonal_arriba_izquierda": (-1, -1),
        }

        acciones_validas = []
        for accion, (dx, dy) in movimientos.items():
            nuevo_x, nuevo_y = x + dx, y + dy
            if 0 <= nuevo_x < self.ambiente.filas and 0 <= nuevo_y < self.ambiente.columnas:
                if self.ambiente.mapa_original[nuevo_x][nuevo_y] != 'X':  # No moverse a obstáculos
                    nivel_actual = self.ambiente.mapa_original[x][y]
                    nivel_nuevo = self.ambiente.mapa_original[nuevo_x][nuevo_y]
                    if abs(nivel_actual - nivel_nuevo) <= 1:  # Verificar cambio de nivel aceptable
                        costo_movimiento = nivel_nuevo + 1  # Calcular costo basado en el nivel
                        if gasolina >= costo_movimiento:
                            acciones_validas.append(accion)

        return acciones_validas

    def result(self, state, action):
        """ Retorna el nuevo estado después de realizar una acción """
        (x, y), gasolina = state
        movimientos = {
            "derecha": (0, 1),
            "abajo": (1, 0),
            "izquierda": (0, -1),
            "arriba": (-1, 0),
            "diagonal_abajo_derecha": (1, 1),
            "diagonal_abajo_izquierda": (1, -1),
            "diagonal_arriba_derecha": (-1, 1),
            "diagonal_arriba_izquierda": (-1, -1),
        }
        dx, dy = movimientos[action]
        nuevo_x, nuevo_y = x + dx, y + dy
        nivel_nuevo = self.ambiente.mapa_original[nuevo_x][nuevo_y]
        costo_movimiento = nivel_nuevo + 1
        nueva_gasolina = gasolina - costo_movimiento
        return ((nuevo_x, nuevo_y), nueva_gasolina)

    def is_goal(self, state):
        """ Define cuándo se ha encontrado agua """
        (x, y), _ = state
        return self.ambiente.mapa[x][y] == ' ~'  # Agua

    def heuristic(self, state):
        """ Heurística para A* (distancia Manhattan al agua más cercana) """
        (x, y), _ = state
        posiciones_agua = [(i, j) for i in range(self.ambiente.filas) for j in range(self.ambiente.columnas) if self.ambiente.mapa[i][j] == ' ~']
        if not posiciones_agua:
            return float("inf")  # Si no hay agua, heurística infinita
        return min(abs(x - ax) + abs(y - ay) for ax, ay in posiciones_agua)

